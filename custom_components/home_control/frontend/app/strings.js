var LANGS = (typeof LANGS === "object" && LANGS) || {};
LANGS.en = EN;
var STR = EN;

/* Uses the pack of a language ("tr", "pt-BR": the whole code first, then its first part); English fills what a pack lacks. */
function langUse(code) {
  var c = String(code || "en");
  STR = LANGS[c] || LANGS[c.split("-")[0]] || EN;
}

/* The text of a key, with {name} places filled from `vars`. */
function _T(k, vars) {
  var s = STR[k];
  if (s === undefined) s = EN[k];
  if (vars && s !== undefined)
    s = s.replace(/\{([a-z_]+)\}/g, function (all, n) {
      return vars[n] === undefined ? all : vars[n];
    });
  return s;
}
